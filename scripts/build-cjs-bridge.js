#!/usr/bin/env node
// Generates CJS bridge files consumed by Netlify Functions (CJS runtime).
// Source of truth is always the ESM modules under src/core/.
// Run: node scripts/build-cjs-bridge.js
// Called automatically by Netlify build via netlify.toml [build] command.

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { createRequire } from 'module';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

// ── Dynamic imports from ESM source ──────────────────────────────────────────

const {
  SCENARIO_NAMES,
  SCENARIO_META,
  SCENARIO_QUESTIONS,
  NEXT_STEPS,
  POLICY_CATEGORIES,
} = await import(`${root}/src/core/scenarios.js`);

const {
  ANSWERS,
  LEVELS,
  RISK_THRESHOLDS,
  UNKNOWN_WEIGHT_MULTIPLIER,
  computeScore,
  isComplete,
  computeLiveLevel,
} = await import(`${root}/src/core/scoring.js`);

// ── Helpers ───────────────────────────────────────────────────────────────────

function serialize(val) {
  return JSON.stringify(val, null, 2);
}

const BANNER = `// AUTO-GENERATED by scripts/build-cjs-bridge.js — do not edit directly.
// Source of truth: src/core/. Re-run \`npm run build:cjs\` after any changes there.
`;

// ── pac-data.cjs ──────────────────────────────────────────────────────────────

const pacDataCjs = `${BANNER}
'use strict';

const POLICY_CATEGORIES = ${serialize(POLICY_CATEGORIES)};

const SCENARIO_NAMES = ${serialize(SCENARIO_NAMES)};

const SCENARIO_META = ${serialize(SCENARIO_META)};

const SCENARIO_QUESTIONS = ${serialize(SCENARIO_QUESTIONS)};

const NEXT_STEPS = ${serialize(NEXT_STEPS)};

module.exports = { POLICY_CATEGORIES, SCENARIO_NAMES, SCENARIO_META, SCENARIO_QUESTIONS, NEXT_STEPS };
`;

// ── scoring.cjs ───────────────────────────────────────────────────────────────

const scoringCjs = `${BANNER}
'use strict';

const ANSWERS = ${serialize(ANSWERS)};

const LEVELS = ${serialize(LEVELS)};

const RISK_THRESHOLDS = ${serialize(RISK_THRESHOLDS)};

const UNKNOWN_WEIGHT_MULTIPLIER = ${UNKNOWN_WEIGHT_MULTIPLIER};

function computeScore(questions, answers) {
  let weightedNo = 0;
  let totalWeight = 0;
  let hasCriticalFlag = false;
  let countUnknown = 0;
  let countYes = 0;
  let countNo = 0;

  questions.forEach(function(item, i) {
    const answer = answers[i];
    totalWeight += item.weight;

    if (answer === ANSWERS.YES) {
      countYes++;
    } else if (answer === ANSWERS.NO) {
      countNo++;
      weightedNo += item.weight;
      if (item.critical) hasCriticalFlag = true;
    } else if (answer === ANSWERS.UNKNOWN) {
      countUnknown++;
      weightedNo += item.weight * UNKNOWN_WEIGHT_MULTIPLIER;
      if (item.critical) hasCriticalFlag = true;
    }
  });

  const ratio = totalWeight > 0 ? weightedNo / totalWeight : 0;

  const level = hasCriticalFlag
    ? LEVELS.HIGH
    : ratio <= RISK_THRESHOLDS.LOW
    ? LEVELS.LOW
    : ratio <= RISK_THRESHOLDS.ELEVATED
    ? LEVELS.ELEVATED
    : LEVELS.HIGH;

  return { level, hasCriticalFlag, ratio, countYes, countNo, countUnknown, totalWeight, weightedNo };
}

function isComplete(answers, questionCount) {
  return answers.filter(function(a) { return a !== null && a !== undefined; }).length === questionCount;
}

function computeLiveLevel(questions, answers) {
  const answered = answers.filter(function(a) { return a !== null && a !== undefined; });
  if (answered.length === 0) return 'neutral';
  return computeScore(questions, answers).level;
}

module.exports = { ANSWERS, LEVELS, RISK_THRESHOLDS, UNKNOWN_WEIGHT_MULTIPLIER, computeScore, isComplete, computeLiveLevel };
`;

// ── Write files ───────────────────────────────────────────────────────────────

const outDir = resolve(root, 'netlify/functions/lib');
mkdirSync(outDir, { recursive: true });

writeFileSync(resolve(outDir, 'pac-data.cjs'), pacDataCjs, 'utf8');
writeFileSync(resolve(outDir, 'scoring.cjs'), scoringCjs, 'utf8');

console.log('✓ netlify/functions/lib/pac-data.cjs');
console.log('✓ netlify/functions/lib/scoring.cjs');
console.log('build:cjs complete');
